"""Score CAD-direct (step_openings) predictions against HUMAN ground-truth labels.

This is the first honest accuracy measurement of the geometric CP path: prior
claims ("exact, no ML needed") rested ten a 2-part visual check, never a score
against independent human labels. The only non-circular evaluation set is the
overlap between the wscad STEP downloads and the human-labeled JSON corpus
(currently 3 PXC parts; wscad_corpus labels were generated BY step_openings
itself, so scoring against those is circular and only useful as a regression
check via --circular).

FRAME ALIGNMENT (the landmine this script exists to handle): the STEP files'
coordinate frame does NOT match the labeled corpus meshes' frame -- measured:
wscaduniverse_3211813 STEP has bbox dims (8.15, 57.73, 42.2) at origin, while
PXC.3211813.json has dims (57.73, 42.2, 8.15) offset in space, i.e. the axes
are permuted AND translated (and possibly sign-flipped: any proper rotation
built from axis permutations is possible). CAD predictions are made in the
STEP frame, human GT lives in the corpus frame -- comparing them raw would
score ~0 regardless of detector quality. We search all proper (det=+1) signed
axis permutations whose dims match, pick the one minimizing mesh-to-mesh
nearest-neighbour residual, and transform the predictions into the GT frame.
A part whose meshes can't be aligned below --align-tol is EXCLUDED with a loud
warning (e.g. the STEP is a different catalog variant than the labeled part --
measured for 3031238: STEP dims 49.1x35.25x5.15 vs GT 50.69x40.5x5.15).

Uses the SAME matching rules as the ML evaluation (metrics.match_predictions,
Hungarian, dist_thresh 5mm) so CAD and ML numbers are directly comparable.

Usage:
  python cad_eval.py --preds preds_cad.json --gt-dir "C:\\...\\JSON" \\
      --step-dir all_wscad_stp
  python cad_eval.py --preds preds_cad.json --gt-dir wscad_corpus \\
      --step-dir all_wscad_stp --circular   # regression check vs own labels
"""
import os 
import re 
import json 
import glob 
import argparse 
import logging 

import numpy as np 

import json_dataset as jd 
import metrics as mcp 

logger =logging .getLogger (__name__ )

DIST_THRESH_MM =5.0 # same TP match radius as the ML evaluation


# ---------------------------------------------------------------------------
# part-number mapping: wscaduniverse_<catalog>_<timestamp> -> GT part_nr
# ---------------------------------------------------------------------------

_CAT_RE =re .compile (r"^wscaduniverse_([0-9A-Za-z-]+)_")


def catalog_nr (pred_part_nr ):
    """'wscaduniverse_3211813_2026-06-21-...' -> '3211813' (None if no match)."""
    m =_CAT_RE .match (str (pred_part_nr ))
    return m .group (1 )if m else None 


def build_gt_index (gt_dir ):
    """part catalog number -> Part, for every labeled part in gt_dir.

    A corpus part named 'PXC.3211813' or 'wscaduniverse_3211813_...' both index
    under '3211813' so predictions from either naming convention can match.
    """
    index ={}
    for p in jd .iter_parts (gt_dir ):
        s =str (p .part_nr )
        cat =catalog_nr (s )
        if cat is None and "."in s :
            cat =s .split (".",1 )[1 ]# 'PXC.3211813' -> '3211813'
        if cat :
            index [cat ]=p 
    return index 


    # ---------------------------------------------------------------------------
    # frame alignment: STEP frame -> GT-corpus frame
    # ---------------------------------------------------------------------------

def _signed_perm_matrices ():
    """All 24 proper rotations that are signed axis permutations (det=+1)."""
    import itertools 
    out =[]
    for perm in itertools .permutations (range (3 )):
        for signs in itertools .product ((1.0 ,-1.0 ),repeat =3 ):
            R =np .zeros ((3 ,3 ))
            for row ,(col ,s )in enumerate (zip (perm ,signs )):
                R [row ,col ]=s 
            if np .linalg .det (R )>0.5 :# proper rotation only (no mirror)
                out .append (R )
    return out 


_PERMS =_signed_perm_matrices ()


def align_frames (V_step ,V_gt ,sample =500 ,seed =0 ):
    """Find (R, t) mapping STEP-frame points into the GT-corpus frame.

    Searches the 24 proper signed-axis-permutation rotations; for each, t is
    fixed by matching bbox centers, and the candidate is scored by the mean
    nearest-STEP-point distance of a subsample of GT vertices mapped INTO the
    STEP frame. Direction matters: the GT mesh is coarse (~700 verts) while the
    STEP tessellation is dense (~100k), so querying sparse-GT -> dense-STEP
    measures true alignment error (~tessellation resolution when correct),
    whereas the reverse (dense -> sparse) is dominated by the GT's own vertex
    spacing and reads several mm even for a PERFECT alignment.
    Returns (R, t, residual_mm). Small residual = confident alignment; large
    residual = the two meshes are NOT the same geometry (variant/revision).
    """
    from scipy .spatial import cKDTree 
    Vs =np .asarray (V_step ,float )
    Vg =np .asarray (V_gt ,float )
    rng =np .random .default_rng (seed )
    idx =rng .choice (len (Vg ),min (sample ,len (Vg )),replace =False )
    G =Vg [idx ]
    gt_c =0.5 *(Vg .min (0 )+Vg .max (0 ))
    st_c =0.5 *(Vs .min (0 )+Vs .max (0 ))
    tree =cKDTree (Vs )# build before ten the dense mesh
    best =(None ,None ,float ("inf"))
    for R in _PERMS :
        t =gt_c -R @st_c 
        # inverse transform: p_step = R.T @ (p_gt - t)
        Q =(G -t )@R # (R.T @ x) for row-vectors = x @ R
        d ,_ =tree .query (Q ,k =1 )
        res =float (np .mean (d ))
        if res <best [2 ]:
            best =(R ,t ,res )
    return best 


def icp_refine (V_step ,V_gt ,R ,t ,iters =40 ,sample =1500 ,seed =0 ):
    """FAZ 1 (hizalama recovery): kaba align_frames (R,t)'sini point-to-point ICP with INCE oturt.
    align_frames only 24 axis-permutasyonu + bbox-centre arar (kaba); ICP rotasyon/oteleme hatasini
    kapatir -> residual duser -> 'havada' CP'ler mesh yuzeyine oturur -> fake-FN azalir.
    Ayni (R,t) konvansiyonu (x_gt = R@x_step + t; big_arbiter: P0 @ R.T + t). Gercekten FARKLI parcada
    (variant/revizyon) ICP residual'i DUSUREMEZ -> high kalir -> correct sekilde bozuk isaretlenir."""
    from scipy .spatial import cKDTree 
    Vs =np .asarray (V_step ,float );Vg =np .asarray (V_gt ,float )
    tree =cKDTree (Vs )
    idx =np .random .default_rng (seed ).choice (len (Vg ),min (sample ,len (Vg )),replace =False )
    G =Vg [idx ]
    R =np .asarray (R ,float ).copy ();t =np .asarray (t ,float ).copy ()
    prev =float ("inf")
    for _ in range (iters ):
        s_est =(G -t )@R # GT'yi STEP frame'e tasi (mevcut ters map)
        d ,j =tree .query (s_est ,k =1 )
        S =Vs [j ]# matched STEP noktalari
        res =float (np .mean (d ))
        if abs (prev -res )<1e-4 :break 
        prev =res 
        Sc =S -S .mean (0 );Gc =G -G .mean (0 )# Kabsch: R,t mapping STEP->GT (R@S+t ~ G)
        H =Sc .T @Gc 
        U ,_ ,Vt =np .linalg .svd (H )
        dsign =np .sign (np .linalg .det (Vt .T @U .T ))
        Rn =Vt .T @np .diag ([1.0 ,1.0 ,dsign ])@U .T 
        tn =G .mean (0 )-Rn @S .mean (0 )
        R ,t =Rn ,tn 
    s_est =(G -t )@R 
    res =float (tree .query (s_est ,k =1 )[0 ].mean ())
    return R ,t ,res 


def align_frames_icp (V_step ,V_gt ,sample =500 ,seed =0 ):
    """kaba align_frames + ICP refine. Returns (R, t, residual_icp)."""
    R ,t ,_ =align_frames (V_step ,V_gt ,sample =sample ,seed =seed )
    return icp_refine (V_step ,V_gt ,R ,t ,seed =seed )


    # ---------------------------------------------------------------------------
    # scoring
    # ---------------------------------------------------------------------------

def score_part (pred_cps ,R ,t ,gt_pts ,gt_dirs ):
    """Transform CAD preds into the GT frame and score with the shared
    keypoint_report (Hungarian matching, DIST_THRESH_MM)."""
    preds =[]
    for cp in pred_cps :
        pt =R @np .asarray (cp ["entry_point"],float )+t 
        dv =R @np .asarray (cp ["approach_vector"],float )
        preds .append ({"point":pt ,"direction":dv })
    return mcp .keypoint_report (preds ,gt_pts ,gt_dirs ,
    dist_thresh_mm =DIST_THRESH_MM ),preds 


def main (argv =None ):
    ap =argparse .ArgumentParser (
    description ="score CAD-direct predictions vs human GT labels "
    "(frame-aligned, Hungarian-matched, ML-comparable)")
    ap .add_argument ("--preds",required =True ,
    help ="step_openings --out JSON (detector predictions)")
    ap .add_argument ("--gt-dir",required =True ,dest ="gt_dir",
    help ="labeled corpus dir (e.g. the ABB/PXC JSON corpus)")
    ap .add_argument ("--step-dir",required =True ,dest ="step_dir",
    help ="dir holding the .stp files the preds were made from "
    "(needed to tessellate for frame alignment)")
    ap .add_argument ("--deflection",type =float ,default =0.3 ,
    help ="alignment-mesh tessellation coarseness (mm); 0.3 is "
    "plenty for bbox/NN alignment and much faster than 0.1")
    ap .add_argument ("--align-tol",type =float ,default =2.0 ,dest ="align_tol",
    help ="max acceptable alignment residual (mm); parts above "
    "this are excluded as different-geometry variants")
    ap .add_argument ("--circular",action ="store_true",
    help ="acknowledge the GT was generated by the same tool "
    "(regression check, not an honest accuracy claim)")
    ap .add_argument ("--out",default =None ,help ="optional results JSON")
    args =ap .parse_args (argv )
    logging .basicConfig (level =logging .INFO ,format ="%(message)s")

    import step_to_json as sj 

    with open (args .preds ,encoding ="utf-8")as fh :
        preds_doc =json .load (fh )
    gt_index =build_gt_index (args .gt_dir )
    logger .info ("GT index: %d labeled parts under %s",len (gt_index ),args .gt_dir )

    rows ,results =[],[]
    tot_tp =tot_fp =tot_fn =0 
    ang_errs =[]
    for part in preds_doc .get ("parts",[]):
        cat =catalog_nr (part ["part_nr"])or str (part ["part_nr"])
        gt =gt_index .get (cat )
        if gt is None :
            continue # no human GT for this part
            # frame alignment needs the STEP mesh
        steps =glob .glob (os .path .join (args .step_dir ,f"*{cat }*.st*p"))
        if not steps :
            logger .warning ("%s: no STEP file under %s -- skipped",cat ,args .step_dir )
            continue 
        V_step ,_F =sj .load_any_mesh (steps [0 ],deflection =args .deflection )
        V_gt =np .asarray (gt .vertices ,float )
        R ,t ,res =align_frames (V_step ,V_gt )
        if res >args .align_tol :
            logger .warning (
            "%s: best frame alignment residual %.2fmm > %.1fmm tolerance -- "
            "STEP geometry does not match the labeled part (different "
            "catalog variant/revision?). EXCLUDED from scoring.",
            cat ,res ,args .align_tol )
            continue 
        _ ,gt_pts ,gt_dirs =jd .dedup_connection_points (gt )
        rep ,tp_preds =score_part (part .get ("connection_points",[]),R ,t ,
        gt_pts ,gt_dirs )
        tot_tp +=rep ["tp"];tot_fp +=rep ["fp"];tot_fn +=rep ["fn"]
        if isinstance (rep .get ("mean_ang_err_deg"),float )and not np .isnan (rep ["mean_ang_err_deg"]):
            ang_errs .append (rep ["mean_ang_err_deg"])
        rows .append ((str (gt .part_nr ),len (gt_pts ),rep ,res ))
        results .append ({"part_nr":str (gt .part_nr ),"catalog":cat ,
        "align_residual_mm":res ,
        "n_gt":int (len (gt_pts )),
        "tp":rep ["tp"],"fp":rep ["fp"],"fn":rep ["fn"],
        "precision":rep ["precision"],"recall":rep ["recall"],
        "f1":rep ["f1"],
        "mean_loc_err_mm":rep ["mean_loc_err_mm"],
        "mean_ang_err_deg":rep ["mean_ang_err_deg"]})

    if not rows :
        raise SystemExit ("no parts could be scored (no GT overlap, or all "
        "excluded by alignment) -- nothing to report")

    tag ="CIRCULAR regression check (GT generated by the same tool!)"if args .circular else "honest accuracy vs independent human GT"
    print (f"\n=== CAD-direct evaluation: {tag } ===")
    print (f"{'part':22s} {'nGT':>4} {'TP':>3} {'FP':>3} {'FN':>3} "
    f"{'P':>6} {'R':>6} {'F1':>6} {'loc':>7} {'ang':>7} {'align':>6}")
    for pn ,ngt ,rep ,res in rows :
        loc =rep ["mean_loc_err_mm"];ang =rep ["mean_ang_err_deg"]
        loc_s ="  -  "if (isinstance (loc ,float )and np .isnan (loc ))else f"{loc :5.2f}"
        ang_s ="  -  "if (isinstance (ang ,float )and np .isnan (ang ))else f"{ang :5.1f}"
        print (f"{pn :22s} {ngt :4d} {rep ['tp']:3d} {rep ['fp']:3d} {rep ['fn']:3d} "
        f"{rep ['precision']:6.2f} {rep ['recall']:6.2f} {rep ['f1']:6.2f} "
        f"{loc_s :>7} {ang_s :>7} {res :5.2f}mm")
    prec =tot_tp /(tot_tp +tot_fp )if (tot_tp +tot_fp )else 0.0 
    rec =tot_tp /(tot_tp +tot_fn )if (tot_tp +tot_fn )else 0.0 
    f1 =2 *prec *rec /(prec +rec )if (prec +rec )else 0.0 
    print (f"\nPOOLED: TP={tot_tp } FP={tot_fp } FN={tot_fn }  "
    f"P={100 *prec :.1f}%  R={100 *rec :.1f}%  F1={100 *f1 :.1f}%"
    +(f"  ang={np .mean (ang_errs ):.1f}deg"if ang_errs else ""))
    print (f"(matching: Hungarian, dist<= {DIST_THRESH_MM }mm -- identical to the "
    f"ML evaluation, so this number is directly comparable to model F1)")

    if args .out :
        doc ={"mode":"circular"if args .circular else "honest",
        "dist_thresh_mm":DIST_THRESH_MM ,
        "pooled":{"tp":tot_tp ,"fp":tot_fp ,"fn":tot_fn ,
        "precision":prec ,"recall":rec ,"f1":f1 },
        "parts":results }
        with open (args .out ,"w",encoding ="utf-8")as fh :
            json .dump (doc ,fh ,indent =1 )
        print (f"results -> {args .out }")


def _selftest ():
    """Perfect predictions under a known rotation+translation must score F1=1."""
    rng =np .random .default_rng (3 )
    V_gt =rng .uniform (0 ,50 ,(300 ,3 ))
    R_true =np .array ([[0 ,1 ,0 ],[0 ,0 ,1 ],[1 ,0 ,0 ]],float )# proper perm
    t_true =np .array ([10.0 ,-5.0 ,2.0 ])
    # STEP frame = inverse transform of the GT frame
    V_step =(V_gt -t_true )@R_true # R^-1 = R.T for rotation; (R.T).T = R
    R ,t ,res =align_frames (V_step ,V_gt )
    assert res <1.0 ,f"alignment failed, residual {res }"
    gt_pts =V_gt [:3 ].copy ()
    gt_dirs =np .tile ([0.0 ,0.0 ,1.0 ],(3 ,1 ))
    pred_cps =[{"entry_point":(R .T @(p -t )).tolist (),
    "approach_vector":(R .T @np .array ([0 ,0 ,1.0 ])).tolist ()}
    for p in gt_pts ]
    rep ,_ =score_part (pred_cps ,R ,t ,gt_pts ,gt_dirs )
    assert rep ["tp"]==3 and rep ["fp"]==0 and rep ["fn"]==0 ,rep 
    print ("cad_eval selftest OK: alignment residual %.3fmm, 3/3 TP"%res )


if __name__ =="__main__":
    import sys 
    if len (sys .argv )==1 :
        _selftest ()
    else :
        main ()
